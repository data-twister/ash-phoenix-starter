  use Ash.Resource,
    domain: AshPhoenixStarter.Accounts,
    data_layer: Ash.DataLayer.Postgres,
    # 1. Register the automated PubSub notifier extension here
    notifiers: [Ash.Notifier.PubSub] 

  attributes do
    uuid_primary_key :id
    attribute :region_name, :string, allow_nil?: false # e.g., "California", "Brittany"
    attribute :qty, :integer, allow_nil?: false, default: 0
    
    timestamps()
  end

  # ... your actions and relationships blocks stay as they are

  # 2. Configure how Ash automatically streams modifications to the map
  pub_sub do
    # Directs Ash to use your existing application PubSub framework
    module AshPhoenixStarterWeb.Endpoint 

    # All topic event broadcasts generated by this file start with this prefix
    prefix "merchant_stock"

    # CRITICAL: Broadcasts an atomic update notification event whenever an update action hits this resource
    # Output topic syntax format generated: "merchant_stock:update"
    publish :update, "update"
  end
end
