defmodule AshPhoenixStarter.Merchants.Product do
  use Ash.Resource,
    otp_app: :ash_phoenix_starter,
    domain: AshPhoenixStarter.Merchants,
    data_layer: AshPostgres.DataLayer,
    notifiers: [Ash.Notifier.PubSub]

  postgres do
    table "products"
  end

  multitenancy do
    strategy :context
  end

  preparations do
    prepare AshPhoenixStarter.Preparations.SetTenant
  end

  changes do
    change AshPhoenixStarter.Changes.SetTenant
  end

  attributes do
    uuid_primary_key :id do
      generated? true
      allow_nil? true
      writable? false
    end

    attribute :name, :string do
      allow_nil? false
      public? true
    end
    
    attribute :price, :integer do
      allow_nil? false
      public? true
    end

    attribute :remaining_stock, :integer do
      allow_nil? false
      default: 0
      public? true
    end

    attribute :low_stock_threshold, :integer do
      allow_nil? false
      default: 2000
      public? true
    end

    attribute :critical_stock_threshold, :integer do
      allow_nil? false
      default: 500
      public? true
    end

    # Database-managed timestamps
    attribute :inserted_at, :utc_datetime_usec do
      generated? true
      allow_nil? true
      writable? false
    end

    attribute :updated_at, :utc_datetime_usec do
      generated? true
      allow_nil? true
      writable? false
    end
  end

  relationships do
    belongs_to :merchant, AshPhoenixStarter.Merchants.Merchant do
      attribute_type :uuid
      allow_nil? false
      public? true
    end
  end

  calculations do
    # Dynamically calculates the alert level used in your layout template table
    calculate :alert_level, :atom, expr(
      if remaining_stock <= critical_stock_threshold do
        :critical
      else
        if remaining_stock <= low_stock_threshold do
          :low
        else
          :ok
        end
      end
    ) do
      public? true
    end
  end

  actions do
    defaults [:read, :destroy]

    create :create do
      primary? true
      accept [:name, :remaining_stock, :price, :low_stock_threshold, :critical_stock_threshold, :merchant_id]
    end

    update :update do
      primary? true
      accept [:name, :remaining_stock, :price, :low_stock_threshold, :critical_stock_threshold, :merchant_id]
    end
  end

    pub_sub do
    module AshPhoenixStarterWeb.Endpoint # Your app's Endpoint module name
    prefix "products"

    # Broadcasts whenever the update action triggers
    publish :update, ["merchant", :id], "updated"

     # All topic event broadcasts generated by this file start with this prefix
    # prefix "merchant_stock"

    # # CRITICAL: Broadcasts an atomic update notification event whenever an update action hits this resource
    # # Output topic syntax format generated: "merchant_stock:update"
    # publish :update, "update"
  end
end
